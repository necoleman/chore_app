// phones in different zones on the same local date get the same fact.
function dayNumber(dateStr) {
  const [y, m, d] = String(dateStr).slice(0, 10).split('-').map(Number);
  if (!y || !m || !d) return 0;
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000);
}

// A small per-person offset so lists of equal length don't all advance in step
// and restart on the same day.
function personOffset(personId) {
  let n = 0;
  for (let i = 0; i < personId.length; i++) n = (n + personId.charCodeAt(i) * (i + 1)) % 997;
  return n;
}

// Today's fact for a person, or '' when there's no list for them — a new family
// member simply has no fact until one is written, rather than breaking the card.
export function factFor(personId, dateStr) {
  const list = PERSON_FACTS[personId];
  if (!list || list.length === 0) return '';
  const idx = (dayNumber(dateStr) + personOffset(personId)) % list.length;
  return list[idx];
}
